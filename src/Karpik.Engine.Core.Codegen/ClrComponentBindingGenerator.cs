using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Karpik.Engine.Core.Codegen;

[Generator]
public sealed class ClrComponentBindingGenerator : IIncrementalGenerator
{
    private const string Common = "Karpik.Engine.Shared.Modding.Bindings.ClrComponentBindings";
    private const string Facade = "Karpik.Engine.Shared.Modding.Lua.LuaComponentRegistry";
    private static readonly DiagnosticDescriptor Unsupported = new("KEB001", "Unsupported CLR binding",
        "Cannot generate component binding: {0}", "ECS", DiagnosticSeverity.Error, true);

    public void Initialize(IncrementalGeneratorInitializationContext context) =>
        context.RegisterSourceOutput(context.CompilationProvider, Execute);

    internal static string ProviderName(Compilation compilation) => "Karpik.Generated.Bindings_" +
        string.Concat((compilation.AssemblyName ?? "Bindings").Select(c => char.IsLetterOrDigit(c) ? c.ToString() : "_" + ((int)c).ToString("X4", System.Globalization.CultureInfo.InvariantCulture))) +
        ".GeneratedClrComponentBindingProvider";

    internal static List<(ITypeSymbol Type, Location Location)> Registrations(Compilation compilation)
    {
        var result = new List<(ITypeSymbol, Location)>();
        foreach (SyntaxTree tree in compilation.SyntaxTrees)
        {
            SemanticModel model = compilation.GetSemanticModel(tree);
            foreach (InvocationExpressionSyntax call in tree.GetRoot().DescendantNodes().OfType<InvocationExpressionSyntax>())
            {
                if (model.GetSymbolInfo(call).Symbol is not IMethodSymbol method || method.Name != "Register" || method.TypeArguments.Length != 1)
                    continue;
                string owner = method.ContainingType.ToDisplayString();
                if (owner != Common && owner != Facade) continue;
                if (model.GetEnclosingSymbol(call.SpanStart)?.ContainingType?.ToDisplayString() == Facade) continue;
                ITypeSymbol type = method.TypeArguments[0];
                if (!result.Any(item => SymbolEqualityComparer.Default.Equals(item.Item1, type)))
                    result.Add((type, call.GetLocation()));
            }
        }
        return result;
    }

    private static void Execute(SourceProductionContext context, Compilation compilation)
    {
        var registrations = Registrations(compilation);
        if (registrations.Count == 0 || compilation.GetTypeByMetadataName(Common) is null) return;
        var models = new List<BindingModel>();
        foreach (var registration in registrations)
        {
            if (registration.Type is not INamedTypeSymbol type || !type.IsUnmanagedType ||
                !compilation.IsSymbolAccessibleWithin(type, compilation.Assembly))
            {
                context.ReportDiagnostic(Diagnostic.Create(Unsupported, registration.Location, registration.Type.ToDisplayString()));
                continue;
            }
            if (!TryCreateModel(type, out var model, out string? error))
            {
                context.ReportDiagnostic(Diagnostic.Create(Unsupported, registration.Location, error));
                continue;
            }
            models.Add(model!);
        }
        if (models.Count == 0) return;
        string name = ProviderName(compilation);
        int separator = name.LastIndexOf('.');
        var source = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        source.Append("namespace ").Append(name.Substring(0, separator)).AppendLine(";");
        source.AppendLine("[global::System.Composition.Export(typeof(global::Karpik.Engine.Shared.Modding.Bindings.IClrComponentBindingProvider))]");
        source.AppendLine("[global::Karpik.Engine.Core.ServiceRegistration(global::Karpik.Engine.Core.ModuleScope.Engine, global::Karpik.Engine.Core.ServiceLifetime.Singleton)]");
        source.Append("public sealed ").Append(models.Any(model => model.Leaves.Any(leaf => leaf.Pointer || leaf.FixedBuffer is not null)) ? "unsafe " : "")
            .AppendLine("class GeneratedClrComponentBindingProvider : global::Karpik.Engine.Shared.Modding.Bindings.IClrComponentBindingProvider {");
        source.Append("private readonly global::Karpik.Engine.Shared.Modding.Bindings.ClrComponentBindingDescriptor[] _bindings = new global::Karpik.Engine.Shared.Modding.Bindings.ClrComponentBindingDescriptor[] {");
        for (int i = 0; i < models.Count; i++) source.Append("new Binding").Append(i).Append("(),");
        source.AppendLine("};");
        source.AppendLine("public global::System.ReadOnlyMemory<global::Karpik.Engine.Shared.Modding.Bindings.ClrComponentBindingDescriptor> GetBindings() => _bindings;");
        for (int i = 0; i < models.Count; i++) EmitBinding(source, models[i], i);
        source.AppendLine("}");
        context.AddSource("ClrComponentBindings.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
    }

    private static bool TryCreateModel(INamedTypeSymbol type, out BindingModel? model, out string? error)
    {
        if (IsInlineArray(type))
        {
            model = null;
            error = type.ToDisplayString() + ": InlineArray layouts are not supported; use a native fixed buffer or explicit unmanaged fields";
            return false;
        }
        var leaves = new List<Leaf>();
        var pending = new Stack<(IFieldSymbol Field, string Code, string Display, bool CanWrite, List<(string? Name, int Index)> Path, List<INamedTypeSymbol> Ancestors)>();
        foreach (IFieldSymbol field in Fields(type))
            pending.Push((field, "", "", true, new List<(string?, int)>(), new List<INamedTypeSymbol> { type }));
        while (pending.Count != 0)
        {
            var item = pending.Pop();
            IFieldSymbol field = item.Field;
            string code = item.Code.Length == 0 ? "@" + field.Name : item.Code + ".@" + field.Name;
            string display = item.Display.Length == 0 ? field.Name : item.Display + "." + field.Name;
            bool canWrite = item.CanWrite && !field.IsReadOnly;
            var path = new List<(string? Name, int Index)>(item.Path) { (field.Name, 0) };
            if (field.IsFixedSizeBuffer && field.Type is IPointerTypeSymbol fixedType && ScalarType(fixedType.PointedAtType) is { } elementType)
            {
                for (int index = 0; index < field.FixedSize; index++)
                {
                    var elementPath = new List<(string? Name, int Index)>(path) { (null, index + 1) };
                    leaves.Add(new Leaf(fixedType.PointedAtType, elementType, code, display + "[" + (index + 1) + "]", canWrite, elementPath, code, index));
                }
                continue;
            }
            if (field.Type is IPointerTypeSymbol)
            {
                leaves.Add(new Leaf(field.Type, "global::Karpik.Engine.Shared.Modding.Bindings.ComponentPointerValue", code, display, canWrite, path, null, 0));
                continue;
            }
            if (ScalarType(field.Type) is { } scalarType)
            {
                leaves.Add(new Leaf(field.Type, scalarType, code, display, canWrite, path, null, 0));
                continue;
            }
            if (field.Type is INamedTypeSymbol nested && nested.IsUnmanagedType && nested.TypeKind == TypeKind.Struct)
            {
                if (IsInlineArray(nested))
                {
                    model = null;
                    error = type.ToDisplayString() + "." + display + ": InlineArray layouts are not supported; use a native fixed buffer or explicit unmanaged fields";
                    return false;
                }
                IFieldSymbol[] children = Fields(nested).ToArray();
                if (children.Length != 0 && !item.Ancestors.Any(parent => SymbolEqualityComparer.Default.Equals(parent, nested)))
                {
                    var ancestors = new List<INamedTypeSymbol>(item.Ancestors) { nested };
                    foreach (IFieldSymbol child in children)
                        pending.Push((child, code, display, canWrite, path, ancestors));
                    continue;
                }
            }
            model = null;
            error = type.ToDisplayString() + "." + display + ": unsupported public field layout; expected a supported scalar, enum, unmanaged struct, fixed buffer or opted-in pointer";
            return false;
        }
        model = new BindingModel(type, leaves.OrderBy(leaf => leaf.Name, StringComparer.Ordinal).ToArray());
        error = null;
        return true;
    }

    private static void EmitBinding(StringBuilder source, BindingModel model, int index)
    {
        string type = model.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        bool pointers = model.Leaves.Any(leaf => leaf.Pointer);
        source.Append("private sealed class Binding").Append(index).AppendLine(" : global::Karpik.Engine.Shared.Modding.Bindings.ClrComponentBindingDescriptor {");
        source.Append("public override global::System.Type ComponentType => typeof(").Append(type).AppendLine(");");
        source.Append("public override global::Karpik.Engine.Shared.Modding.Bindings.IComponentPoolAccess Bind(global::DCFApixels.DragonECS.EcsDefaultWorld world) => ");
        if (pointers)
        {
            source.AppendLine("throw new global::System.InvalidOperationException(\"Native pointer components require explicit host pointer policy.\");");
            source.Append("public override global::Karpik.Engine.Shared.Modding.Bindings.IComponentPoolAccess Bind(global::DCFApixels.DragonECS.EcsDefaultWorld world, global::Karpik.Engine.Shared.Modding.Bindings.ComponentPointerRegistry pointers) => new Pool").Append(index).AppendLine("(world, pointers); }");
        }
        else source.Append("new Pool").Append(index).AppendLine("(world); }");
        source.Append("private sealed class Pool").Append(index).Append(" : global::Karpik.Engine.Shared.Modding.Bindings.ClrComponentPool<").Append(type).AppendLine("> {");
        if (pointers)
        {
            source.AppendLine("private readonly global::Karpik.Engine.Shared.Modding.Bindings.ComponentPointerRegistry _pointers;");
            for (int field = 0; field < model.Leaves.Length; field++)
                if (model.Leaves[field].Pointer) source.Append("private readonly global::Karpik.Engine.Shared.Modding.Bindings.ComponentPointerType _pointer").Append(field).AppendLine(";");
        }
        source.AppendLine("public override global::System.ReadOnlyMemory<global::Karpik.Engine.Shared.Modding.Bindings.ComponentFieldDescriptor> Fields { get; }");
        source.Append("public Pool").Append(index).Append("(global::DCFApixels.DragonECS.EcsDefaultWorld world");
        if (pointers) source.Append(", global::Karpik.Engine.Shared.Modding.Bindings.ComponentPointerRegistry pointers");
        source.AppendLine(") : base(world) {");
        if (pointers)
        {
            source.AppendLine("_pointers = pointers ?? throw new global::System.ArgumentNullException(nameof(pointers));");
            for (int field = 0; field < model.Leaves.Length; field++)
                if (model.Leaves[field].Pointer) source.Append("_pointer").Append(field).Append(" = pointers.ResolveNativeType(typeof(").Append(model.Leaves[field].Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)).AppendLine("));");
        }
        source.AppendLine("Fields = new global::Karpik.Engine.Shared.Modding.Bindings.ComponentFieldDescriptor[] {");
        for (int field = 0; field < model.Leaves.Length; field++)
        {
            Leaf leaf = model.Leaves[field];
            source.Append("new(").Append(Literal(leaf.Name)).Append(", ").Append(leaf.CanWrite ? "true" : "false").Append(", new Field").Append(field).Append("(this))");
            if (leaf.Path.Count > 1 || leaf.Pointer)
            {
                source.Append(" { ");
                if (leaf.Path.Count > 1)
                {
                    source.Append("Path = new global::Karpik.Engine.Shared.Modding.Bindings.ComponentPathSegment[] {");
                    foreach (var segment in leaf.Path)
                        source.Append("new(").Append(segment.Name is null ? "null" : Literal(segment.Name)).Append(", ").Append(segment.Index).Append("),");
                    source.Append("}, ");
                }
                if (leaf.Pointer) source.Append("PointerRegistry = _pointers, PointerType = _pointer").Append(field).Append(", ");
                source.Append("}");
            }
            source.AppendLine(",");
        }
        source.AppendLine("}; }");
        for (int field = 0; field < model.Leaves.Length; field++) EmitField(source, model.Leaves[field], index, field);
        source.AppendLine("}");
    }

    private static void EmitField(StringBuilder source, Leaf leaf, int pool, int index)
    {
        source.Append("private sealed class Field").Append(index).Append(" : global::Karpik.Engine.Shared.Modding.Bindings.IComponentField<").Append(leaf.AccessorType).AppendLine("> {");
        source.Append("private readonly Pool").Append(pool).AppendLine(" _owner;");
        source.Append("public Field").Append(index).Append("(Pool").Append(pool).AppendLine(" owner) { _owner = owner; }");
        source.Append("public ").Append(leaf.AccessorType).Append(" Read(int entityId) ");
        if (leaf.FixedBuffer is not null)
            source.Append("{ fixed (").Append(leaf.AccessorType).Append("* values = _owner.ReadComponent(entityId).").Append(leaf.FixedBuffer).Append(") { return values[").Append(leaf.FixedIndex).AppendLine("]; } }");
        else if (leaf.Pointer)
            source.Append("=> _owner._pointers.Capture(_owner._pointer").Append(index).Append(", (nuint)_owner.ReadComponent(entityId).").Append(leaf.Code).AppendLine(");");
        else
            source.Append("=> ").Append(leaf.Type.TypeKind == TypeKind.Enum ? "(" + leaf.AccessorType + ")" : "").Append("_owner.ReadComponent(entityId).").Append(leaf.Code).AppendLine(";");
        source.Append("public void Write(int entityId, ").Append(leaf.AccessorType).Append(" value) ");
        if (!leaf.CanWrite) source.AppendLine("=> throw new global::System.InvalidOperationException(\"Field is readonly.\");");
        else if (leaf.FixedBuffer is not null)
            source.Append("{ fixed (").Append(leaf.AccessorType).Append("* values = _owner.MutableComponent(entityId).").Append(leaf.FixedBuffer).Append(") { values[").Append(leaf.FixedIndex).AppendLine("] = value; } }");
        else if (leaf.Pointer)
            source.Append("{ nuint address = _owner._pointers.ReadAddress(value, _owner._pointer").Append(index).Append("); _owner.MutableComponent(entityId).").Append(leaf.Code).Append(" = (").Append(leaf.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)).AppendLine(")address; }");
        else
            source.Append("=> _owner.MutableComponent(entityId).").Append(leaf.Code).Append(" = ").Append(leaf.Type.TypeKind == TypeKind.Enum ? "(" + leaf.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + ")" : "").AppendLine("value;");
        source.AppendLine("}");
    }

    private static string Literal(string value) => Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(value, quote: true);

    private sealed class BindingModel
    {
        internal readonly INamedTypeSymbol Type;
        internal readonly Leaf[] Leaves;
        internal BindingModel(INamedTypeSymbol type, Leaf[] leaves) { Type = type; Leaves = leaves; }
    }

    private sealed class Leaf
    {
        internal readonly ITypeSymbol Type;
        internal readonly string AccessorType;
        internal readonly string Code;
        internal readonly string Name;
        internal readonly bool CanWrite;
        internal readonly List<(string? Name, int Index)> Path;
        internal readonly string? FixedBuffer;
        internal readonly int FixedIndex;
        internal bool Pointer => Type is IPointerTypeSymbol;
        internal Leaf(ITypeSymbol type, string accessorType, string code, string name, bool canWrite, List<(string? Name, int Index)> path, string? fixedBuffer, int fixedIndex)
        { Type = type; AccessorType = accessorType; Code = code; Name = name; CanWrite = canWrite; Path = path; FixedBuffer = fixedBuffer; FixedIndex = fixedIndex; }
    }

    private static bool IsInlineArray(INamedTypeSymbol type) => type.GetAttributes().Any(attribute =>
        attribute.AttributeClass?.ToDisplayString() == "System.Runtime.CompilerServices.InlineArrayAttribute");

    private static IEnumerable<IFieldSymbol> Fields(INamedTypeSymbol type) => type.GetMembers().OfType<IFieldSymbol>()
        .Where(field => !field.IsStatic && !field.IsImplicitlyDeclared && field.DeclaredAccessibility == Accessibility.Public);

    private static string? ScalarType(ITypeSymbol type) => type is INamedTypeSymbol { TypeKind: TypeKind.Enum, EnumUnderlyingType: not null } enumeration
        ? ScalarType(enumeration.EnumUnderlyingType)
        : type.SpecialType switch
    {
        SpecialType.System_Boolean => "bool",
        SpecialType.System_Int32 => "int",
        SpecialType.System_UInt32 => "uint",
        SpecialType.System_Single => "float",
        SpecialType.System_Double => "double",
        SpecialType.System_SByte => "sbyte",
        SpecialType.System_Byte => "byte",
        SpecialType.System_Int16 => "short",
        SpecialType.System_UInt16 => "ushort",
        SpecialType.System_Char => "char",
        SpecialType.System_Int64 => "long",
        SpecialType.System_UInt64 => "ulong",
        SpecialType.System_Decimal => "decimal",
        SpecialType.System_IntPtr => "nint",
        SpecialType.System_UIntPtr => "nuint",
        _ => null
    };
}
