using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Karpik.Engine.Core.Codegen;

[Generator]
public sealed class ClrComponentBindingGenerator : IIncrementalGenerator
{
    private const string Common = "Karpik.Engine.Shared.Modding.Bindings.ClrComponentBindings";
    private const string Facade = "Karpik.Engine.Shared.Modding.Lua.LuaComponentRegistry";
    private static readonly DiagnosticDescriptor Unsupported = new("KEB001", "Unsupported CLR binding",
        "Cannot generate component binding: {0}", "ECS", DiagnosticSeverity.Error, true);

    public void Initialize(IncrementalGeneratorInitializationContext context) =>
        context.RegisterSourceOutput(context.CompilationProvider, Execute);

    internal static string ProviderName(Compilation compilation) => "Karpik.Generated.Bindings_" +
        string.Concat((compilation.AssemblyName ?? "Bindings").Select(c => char.IsLetterOrDigit(c) ? c.ToString() : "_" + ((int)c).ToString("X4", System.Globalization.CultureInfo.InvariantCulture))) +
        ".GeneratedClrComponentBindingProvider";

    internal static List<(ITypeSymbol Type, Location Location)> Registrations(Compilation compilation)
    {
        var result = new List<(ITypeSymbol, Location)>();
        foreach (SyntaxTree tree in compilation.SyntaxTrees)
        {
            SemanticModel model = compilation.GetSemanticModel(tree);
            foreach (InvocationExpressionSyntax call in tree.GetRoot().DescendantNodes().OfType<InvocationExpressionSyntax>())
            {
                if (model.GetSymbolInfo(call).Symbol is not IMethodSymbol method || method.Name != "Register" || method.TypeArguments.Length != 1)
                    continue;
                string owner = method.ContainingType.ToDisplayString();
                if (owner != Common && owner != Facade) continue;
                if (model.GetEnclosingSymbol(call.SpanStart)?.ContainingType?.ToDisplayString() == Facade) continue;
                ITypeSymbol type = method.TypeArguments[0];
                if (!result.Any(item => SymbolEqualityComparer.Default.Equals(item.Item1, type)))
                    result.Add((type, call.GetLocation()));
            }
        }
        return result;
    }

    private static void Execute(SourceProductionContext context, Compilation compilation)
    {
        var registrations = Registrations(compilation);
        if (registrations.Count == 0 || compilation.GetTypeByMetadataName(Common) is null) return;
        var types = new List<INamedTypeSymbol>();
        foreach (var registration in registrations)
        {
            if (registration.Type is not INamedTypeSymbol type || !type.IsUnmanagedType ||
                !compilation.IsSymbolAccessibleWithin(type, compilation.Assembly))
            {
                context.ReportDiagnostic(Diagnostic.Create(Unsupported, registration.Location, registration.Type.ToDisplayString()));
                continue;
            }
            IFieldSymbol? bad = Fields(type).FirstOrDefault(field => field.Type.SpecialType != SpecialType.System_Single || field.IsFixedSizeBuffer);
            if (bad is not null)
            {
                context.ReportDiagnostic(Diagnostic.Create(Unsupported, registration.Location, $"{type.ToDisplayString()}.{bad.Name}: only f32 fields are implemented in this slice"));
                continue;
            }
            types.Add(type);
        }
        if (types.Count == 0) return;
        string name = ProviderName(compilation);
        int separator = name.LastIndexOf('.');
        var source = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        source.Append("namespace ").Append(name.Substring(0, separator)).AppendLine(";");
        source.AppendLine("[global::System.Composition.Export(typeof(global::Karpik.Engine.Shared.Modding.Bindings.IClrComponentBindingProvider))]");
        source.AppendLine("[global::Karpik.Engine.Core.ServiceRegistration(global::Karpik.Engine.Core.ModuleScope.Engine, global::Karpik.Engine.Core.ServiceLifetime.Singleton)]");
        source.AppendLine("public sealed class GeneratedClrComponentBindingProvider : global::Karpik.Engine.Shared.Modding.Bindings.IClrComponentBindingProvider {");
        source.Append("private readonly global::Karpik.Engine.Shared.Modding.Bindings.ClrComponentBindingDescriptor[] _bindings = new global::Karpik.Engine.Shared.Modding.Bindings.ClrComponentBindingDescriptor[] {");
        for (int i = 0; i < types.Count; i++) source.Append("new Binding").Append(i).Append("(),");
        source.AppendLine("};");
        source.AppendLine("public global::System.ReadOnlyMemory<global::Karpik.Engine.Shared.Modding.Bindings.ClrComponentBindingDescriptor> GetBindings() => _bindings;");
        for (int i = 0; i < types.Count; i++)
        {
            string type = types[i].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var fields = Fields(types[i]).OrderBy(field => field.Name, StringComparer.Ordinal).ToArray();
            source.Append("private sealed class Binding").Append(i).AppendLine(" : global::Karpik.Engine.Shared.Modding.Bindings.ClrComponentBindingDescriptor {");
            source.Append("public override global::System.Type ComponentType => typeof(").Append(type).AppendLine(");");
            source.Append("public override global::Karpik.Engine.Shared.Modding.Bindings.IComponentPoolAccess Bind(global::DCFApixels.DragonECS.EcsDefaultWorld world) => new Pool").Append(i).AppendLine("(world); }");
            source.Append("private sealed class Pool").Append(i).Append(" : global::Karpik.Engine.Shared.Modding.Bindings.ClrComponentPool<").Append(type).AppendLine("> {");
            source.AppendLine("public override global::System.ReadOnlyMemory<global::Karpik.Engine.Shared.Modding.Bindings.ComponentFieldDescriptor> Fields { get; }");
            source.Append("public Pool").Append(i).AppendLine("(global::DCFApixels.DragonECS.EcsDefaultWorld world) : base(world) {");
            source.AppendLine("Fields = new global::Karpik.Engine.Shared.Modding.Bindings.ComponentFieldDescriptor[] {");
            for (int f = 0; f < fields.Length; f++)
                source.Append("new(\"").Append(fields[f].Name).Append("\", ").Append(fields[f].IsReadOnly ? "false" : "true").Append(", new Field").Append(f).AppendLine("(this)),");
            source.AppendLine("}; }");
            for (int f = 0; f < fields.Length; f++)
            {
                source.Append("private sealed class Field").Append(f).AppendLine(" : global::Karpik.Engine.Shared.Modding.Bindings.IComponentField<float> {");
                source.Append("private readonly Pool").Append(i).AppendLine(" _owner;");
                source.Append("public Field").Append(f).Append("(Pool").Append(i).AppendLine(" owner) { _owner = owner; }");
                source.Append("public float Read(int entityId) => _owner.ReadComponent(entityId).@").Append(fields[f].Name).AppendLine(";");
                source.Append("public void Write(int entityId, float value) ");
                if (fields[f].IsReadOnly) source.AppendLine("=> throw new global::System.InvalidOperationException(\"Field is readonly.\");");
                else source.Append("=> _owner.MutableComponent(entityId).@").Append(fields[f].Name).AppendLine(" = value;");
                source.AppendLine("}");
            }
            source.AppendLine("}");
        }
        source.AppendLine("}");
        context.AddSource("ClrComponentBindings.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
    }

    private static IEnumerable<IFieldSymbol> Fields(INamedTypeSymbol type) => type.GetMembers().OfType<IFieldSymbol>()
        .Where(field => !field.IsStatic && !field.IsImplicitlyDeclared && field.DeclaredAccessibility == Accessibility.Public);
}
